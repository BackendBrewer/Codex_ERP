<?php

namespace App\Http\Requests;

use App\Models\Examination;
use App\Models\FeeInvoice;
use App\Models\FeePayment;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

class ModuleRecordRequest extends FormRequest
{
    /**
     * Determine if the user is authorized to make this request.
     */
    public function authorize(): bool
    {
        $module = (string) $this->route('module');
        $action = $this->isMethod('POST') ? 'store' : 'edit';
        $feature = config('academy_access.module_features.'.$module);
        if ($module === 'fees') {
            $canCreate = $action === 'store' && ($this->user()?->hasFeature('fees.single') ?? false);
            $canUpdate = $action === 'edit' && (($this->user()?->hasFeature('fees.modify') ?? false) || ($this->user()?->hasFeature('fees.reports.adjust') ?? false));

            return $canCreate || $canUpdate;
        } elseif ($module === 'payments') {
            $feature = $action === 'store' ? 'fees.collect' : 'fees.receipts';
        }

        return is_string($feature) && ($this->user()?->hasFeature($feature) ?? false);
    }

    /**
     * Get the validation rules that apply to the request.
     *
     * @return array<string, array<int, mixed>|string>
     */
    public function rules(): array
    {
        $module = (string) $this->route('module');
        $definition = config('academy.modules.'.$module, []);
        $record = $this->route('id') ? ($definition['model'])::query()->find($this->route('id')) : null;
        $rules = [];

        foreach ($definition['fields'] ?? [] as $name => $field) {
            $autoGenerated = $record === null && in_array($name, ['admission_no', 'invoice_no', 'receipt_no', 'employee_no', 'entry_no'], true);
            $rules[$name] = [(($field['required'] ?? false) && ! $autoGenerated) ? 'required' : 'nullable'];
            if (isset($field['options'])) {
                $rules[$name][] = Rule::in(array_keys($field['options']));
            } elseif (isset($field['source'])) {
                $rules[$name][] = 'integer';
                $sourceTable = match ($field['source']) {
                    'classes' => 'academy_classes', 'students' => 'students', 'invoices' => 'fee_invoices', 'exams' => 'examinations', default => 'id',
                };
                $exists = Rule::exists($sourceTable, 'id');
                if ($this->user()?->role === 'admin') {
                    $exists->where('academy_id', $this->user()->academy_id);
                }
                $rules[$name][] = $exists;
            } elseif ($field['type'] === 'number') {
                $rules[$name][] = 'numeric';
                $rules[$name][] = 'min:0';
            } elseif ($field['type'] === 'date') {
                $rules[$name][] = 'date';
            } elseif ($field['type'] === 'month') {
                $rules[$name][] = 'date_format:Y-m';
            } elseif ($field['type'] === 'datetime-local') {
                $rules[$name][] = 'date';
            } else {
                $rules[$name][] = 'string';
                $maxLength = $module === 'messages' && $name === 'message' ? 160 : ($field['type'] === 'textarea' ? 2000 : 255);
                $rules[$name][] = 'max:'.$maxLength;
            }
        }
        if ($module === 'classes') {
            $rules['active'] = ['nullable', 'boolean'];
        }
        if ($module === 'results') {
            $rules['marks_obtained'][] = 'min:0';
            $rules['marks_obtained'][] = 'max:'.(Examination::query()->find($this->input('examination_id'))?->total_marks ?? 999999.99);
        }
        if ($module === 'payments' && $this->filled('fee_invoice_id')) {
            $invoice = FeeInvoice::query()->with('payments')->find($this->integer('fee_invoice_id'));
            if ($invoice !== null) {
                $paid = (float) $invoice->payments->sum('amount');
                if ($this->route('id') !== null) {
                    $currentPayment = FeePayment::query()->find($this->route('id'));
                    if ($currentPayment !== null && (int) $currentPayment->fee_invoice_id === (int) $invoice->id) {
                        $paid -= (float) $currentPayment->amount;
                    }
                }
                $balance = max(0, (float) $invoice->amount - (float) $invoice->discount + (float) $invoice->late_fee - $paid);
                $rules['amount'][] = 'min:0.01';
                $rules['amount'][] = 'max:'.$balance;
            }
        }

        return $rules;
    }
}
